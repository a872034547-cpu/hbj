def get_lang() -> str:
    """获取当前语言设置，默认中文"""
    return st.session_state.get("ui_language", "zh")


def t(key: str, **kwargs) -> str:
    """
    翻译函数：根据当前语言返回对应文本，支持 {placeholder} 格式化。

    Args:
        key: 翻译键名
        **kwargs: 格式化参数

    Returns:
        翻译后的字符串
    """
    lang = get_lang()
    text = TRANSLATIONS.get(lang, TRANSLATIONS["zh"]).get(key)
    if text is None:
        # 回退到中文
        text = TRANSLATIONS["zh"].get(key, key)
    if key == "chapter_item" and "n" in kwargs:
        return format_chapter_label(kwargs.get("n"))
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text
